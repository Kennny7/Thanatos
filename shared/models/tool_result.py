# shared/models/tool_result.py

from typing import Any, Optional
from pydantic import BaseModel, ConfigDict


class ToolResult(BaseModel):
    """
    Canonical representation of a tool execution outcome.

    This model serves as the **single source of truth** for tool results across
    the entire system. Every plugin, the tool dispatcher, and the agent loop
    rely on this structure to communicate success/failure and payload data in a
    consistent, machine‑verifiable way.

    Fields
    ------
    tool_name : str
        The name of the tool that was executed (e.g. `"web_search"`).
    success : bool
        `True` if the tool completed its work without errors, `False` otherwise.
    content : Any, optional
        The result payload returned by a successful execution. Defaults to `None`.
    error : Optional[str], optional
        A human‑readable error message when `success` is `False`. Defaults to `None`.

    Properties
    ----------
    is_error : bool
        Convenience computed property returning `not self.success`.
    """

    model_config = ConfigDict(extra="forbid")

    tool_name: str
    success: bool
    content: Any = None
    error: Optional[str] = None

    @property
    def is_error(self) -> bool:
        """Return True when the tool execution failed."""
        return not self.success

    @classmethod
    def success_result(cls, tool_name: str, content: Any) -> "ToolResult":
        """
        Factory for a successful tool outcome.

        Parameters
        ----------
        tool_name : str
            Name of the tool that produced this result.
        content : Any
            The payload generated by the tool.

        Returns
        -------
        ToolResult
            Instance with `success=True`, `content` set, and `error=None`.
        """
        return cls(tool_name=tool_name, success=True, content=content)

    @classmethod
    def error_result(cls, tool_name: str, error: str) -> "ToolResult":
        """
        Factory for a failed tool outcome.

        Parameters
        ----------
        tool_name : str
            Name of the tool that failed.
        error : str
            Description of what went wrong.

        Returns
        -------
        ToolResult
            Instance with `success=False`, `content=None`, and `error` set.
        """
        return cls(tool_name=tool_name, success=False, error=error)